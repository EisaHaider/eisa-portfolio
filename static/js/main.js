function updateTexts(lang) {
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.dataset.i18n;
        if (translations[lang][key]) {
            el.textContent = translations[lang][key];
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.dataset.i18nPlaceholder;
        if (translations[lang][key]) {
            el.placeholder = translations[lang][key];
        }
    });

    if (typeof lucide !== "undefined") {
        lucide.createIcons();
    }
}

function applyLanguage(lang) {
    localStorage.setItem("language", lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = translations[lang].direction;
    updateTexts(lang);
}

function toggleLanguage() {
    const current = localStorage.getItem("language") || "en";
    const next = current === "en" ? "ar" : "en";
    applyLanguage(next);
}

function applyTheme(theme) {
    localStorage.setItem("theme", theme);
    if (theme === "light") {
        document.documentElement.classList.add("light");
    } else {
        document.documentElement.classList.remove("light");
    }
}

function toggleTheme() {
    const current = localStorage.getItem("theme") || "dark";
    const next = current === "dark" ? "light" : "dark";
    applyTheme(next);
}

function revealElements() {
    const elements = document.querySelectorAll(".fade-up");
    const observer = new IntersectionObserver(
        entries => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add("show");
                }
            });
        },
        { threshold: 0.1 }
    );

    elements.forEach(el => {
        observer.observe(el);
    });
}

function setupContactForm() {
    const form = document.getElementById("contact-form");
    if (!form) {
        return;
    }

    const submitButton = document.getElementById("contact-submit");
    const submitText = submitButton ? submitButton.querySelector("[data-i18n]") : null;
    const status = document.getElementById("contact-status");

    form.addEventListener("submit", async event => {
        event.preventDefault();

        const lang = localStorage.getItem("language") || "en";
        const data = new FormData(form);
        const payload = {
            name: data.get("name") || "",
            email: data.get("email") || "",
            phone: data.get("phone") || "",
            message: data.get("message") || ""
        };

        if (submitButton) {
            submitButton.disabled = true;
            submitButton.classList.add("opacity-70", "cursor-not-allowed");
        }
        if (submitText) {
            submitText.textContent = translations[lang].contact_sending;
        }
        if (status) {
            status.textContent = "";
        }

        try {
            const response = await fetch("/contact", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify(payload)
            });

            if (!response.ok) {
                throw new Error("Contact request failed");
            }

            form.reset();
            if (status) {
                status.textContent = translations[lang].contact_success;
                status.className = "min-h-5 text-sm text-blue-400";
            }
        } catch (error) {
            if (status) {
                status.textContent = translations[lang].contact_error;
                status.className = "min-h-5 text-sm text-red-400";
            }
        } finally {
            if (submitButton) {
                submitButton.disabled = false;
                submitButton.classList.remove("opacity-70", "cursor-not-allowed");
            }
            if (submitText) {
                submitText.textContent = translations[lang].contact_submit;
            }
        }
    });
}

function setupMobileMenu() {
    const menu = document.getElementById("mobile-menu");
    if (!menu) {
        return;
    }

    menu.querySelectorAll("a").forEach(link => {
        link.addEventListener("click", () => {
            menu.open = false;
        });
    });
}

document.addEventListener("DOMContentLoaded", () => {
    const savedLang = localStorage.getItem("language") || "en";
    const savedTheme = localStorage.getItem("theme") || "dark";

    applyLanguage(savedLang);
    applyTheme(savedTheme);

    const langBtn = document.getElementById("language-toggle");
    if (langBtn) {
        langBtn.addEventListener("click", toggleLanguage);
    }

    const themeBtn = document.getElementById("theme-toggle");
    if (themeBtn) {
        themeBtn.addEventListener("click", toggleTheme);
    }

    if (typeof lucide !== "undefined") {
        lucide.createIcons();
    }

    setupContactForm();
    setupMobileMenu();
    revealElements();
});
